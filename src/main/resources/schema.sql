CREATE TABLE IF NOT EXISTS medicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(64) NOT NULL,
    valor DOUBLE PRECISION NOT NULL,
    unidade VARCHAR(20) NOT NULL,
    instante TIMESTAMP(9) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_medicao_sensor_instante
    ON medicao (sensor_id, instante, id);

CREATE TABLE IF NOT EXISTS alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(64) NOT NULL,
    nivel VARCHAR(16) NOT NULL CHECK (nivel IN ('ATENCAO', 'ALERTA', 'CRITICO')),
    valor_previsto DOUBLE PRECISION NOT NULL,
    limiar DOUBLE PRECISION NOT NULL,
    unidade VARCHAR(20) NOT NULL,
    instante TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
